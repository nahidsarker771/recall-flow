package com.studyretention.tracker.ui.theme

import androidx.compose.ui.unit.dp

/**
 * 4dp spacing scale: 4 / 8 / 12 / 16 / 24 / 32, plus a 20dp screen gutter.
 * Every screen should use these tokens instead of ad-hoc dp values.
 */
object Spacing {
    val xxs = 2.dp
    val xs = 4.dp
    val sm = 8.dp
    val md = 12.dp
    val lg = 16.dp
    val xl = 24.dp
    val xxl = 32.dp

    /** Horizontal gutter used by every top-level screen. */
    val screen = 20.dp
}
